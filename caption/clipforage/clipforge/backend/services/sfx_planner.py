import json
import hashlib
import logging
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select
from backend.models.models import SFXAsset, ClipRetention, ClipSFXPlan, Clip, Video, Job, Channel
from backend.models.sfx import SFXPlacement, SFXPlan

logger = logging.getLogger(__name__)

class SFXPlanner:
    def __init__(self, 
                 ducking_target_gain: float = -15.0, 
                 default_gain: float = -10.0,
                 max_concurrent_sfx: int = 2):
        self.ducking_target_gain = ducking_target_gain
        self.default_gain = default_gain
        self.max_concurrent_sfx = max_concurrent_sfx

    @staticmethod
    async def _is_trusted_test_clip(db: AsyncSession, clip_id: str, explicit_is_test: bool | None = None) -> bool:
        """
        Authoritatively verifies whether a clip executes within a trusted test-fixture context.
        Resolves test status strictly through verified database relationships (Job.is_test, Channel.is_test).
        Missing, ambiguous, conflicting, or unverified context fails closed (returns False).
        Identifier prefixes alone never authorize test fallback, and caller-supplied parameters
        cannot turn production clips into test fixtures without database confirmation.
        """
        # If caller explicitly marks clip as non-test, fail closed immediately
        if explicit_is_test is False:
            return False

        if not clip_id:
            return False

        try:
            # 1. Fetch Clip from database
            clip_res = await db.execute(select(Clip).where(Clip.id == clip_id))
            clip = clip_res.scalar_one_or_none()
            if not clip:
                logger.warning(f"Clip {clip_id} not found in database; test context cannot be verified.")
                return False

            # 2. Resolve linked Job
            job = None
            if clip.video_id:
                job_res = await db.execute(
                    select(Job).where(Job.video_id == clip.video_id).order_by(Job.created_at.desc())
                )
                job = job_res.scalars().first()

            if not job and clip.run_identity:
                parts = clip.run_identity.split("_")
                job_id = "_".join(parts[:-2]) if len(parts) > 2 else clip.run_identity
                job_res = await db.execute(select(Job).where(Job.id == job_id))
                job = job_res.scalar_one_or_none()

            # 3. Resolve linked Channel
            channel = None
            if clip.video_id:
                vid_res = await db.execute(select(Video).where(Video.id == clip.video_id))
                video = vid_res.scalar_one_or_none()
                if video and video.channel_id:
                    chan_res = await db.execute(select(Channel).where(Channel.id == video.channel_id))
                    channel = chan_res.scalar_one_or_none()

            if not channel and job and job.channel_id:
                chan_res = await db.execute(select(Channel).where(Channel.id == job.channel_id))
                channel = chan_res.scalar_one_or_none()

            # 4. Enforce Authoritative Database Context & Conflict Detection
            if job is None and channel is None:
                # Missing both job and channel context -> fail closed
                logger.warning(f"No linked Job or Channel found for clip {clip_id}; failing closed.")
                return False

            if job is not None and channel is not None:
                job_flag = bool(job.is_test)
                chan_flag = bool(channel.is_test)
                if job_flag != chan_flag:
                    # Conflicting flags fail closed
                    logger.warning(
                        f"Conflicting test flags for clip {clip_id}: "
                        f"Job.is_test={job_flag}, Channel.is_test={chan_flag}. Failing closed."
                    )
                    return False
                db_is_test = job_flag
            elif job is not None:
                db_is_test = bool(job.is_test)
            else:
                db_is_test = bool(channel.is_test)

            # 5. Database confirmation is strictly required
            if not db_is_test:
                return False

            return True

        except Exception as e:
            logger.warning(f"Could not verify test context for clip {clip_id}: {e}")
            return False

    @staticmethod
    def _is_synthetic_mock_asset(asset: SFXAsset) -> bool:
        """Determines if an SFXAsset is an autogenerated synthetic test tone."""
        if not asset or not asset.name:
            return False
        return (
            asset.name.startswith("sample_")
            or asset.name.startswith("mock_")
            or "trace_tone" in asset.name
        )

    @staticmethod
    async def _mock_generate_asset(db: AsyncSession, category: str, clip_id: str) -> SFXAsset:
        """Generates a sample SFX audio asset via FFmpeg and registers it in DB."""
        import tempfile, os, shutil, uuid, asyncio
        from backend.models.models import ArtifactType, SFXAsset
        from backend.services.artifact_manager import artifact_manager
        
        fd, temp_path = tempfile.mkstemp(suffix=".wav")
        os.close(fd)
        try:
            freq = 440 if category == "impact" else (880 if category == "whoosh" else 220)
            cmd = [
                "ffmpeg", "-y", "-f", "lavfi",
                "-i", f"sine=frequency={freq}:duration=1.0",
                "-c:a", "pcm_s16le", temp_path
            ]
            proc = await asyncio.create_subprocess_exec(
                *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            stdout, stderr = await proc.communicate()
            if proc.returncode != 0:
                raise RuntimeError(f"FFmpeg synthetic tone generation failed (code {proc.returncode}): {stderr.decode()}")
            
            asset_id = str(uuid.uuid4())
            storage_key = f"mock_sfx/{asset_id}.wav"
            async with artifact_manager.managed_upload(
                db=db,
                owner_type="clip",
                owner_id=clip_id,
                artifact_type=ArtifactType.AUDIO_SFX,
                storage_key=storage_key,
                retention_policy="persistent",
                processing_version="mock_1.0"
            ) as upload_path:
                shutil.copy2(temp_path, upload_path)
                
            record = await artifact_manager.get_artifact(db, storage_key)
            if not record:
                raise RuntimeError(f"Failed to retrieve registered artifact for {storage_key}")

            new_asset = SFXAsset(
                id=asset_id,
                pack_id=None,
                artifact_id=record.id,
                name=f"sample_{category}",
                category=category,
                duration=1.0
            )
            db.add(new_asset)
            await db.commit()
            await db.refresh(new_asset)
            return new_asset
        finally:
            if os.path.exists(temp_path):
                os.remove(temp_path)

    @staticmethod
    async def _persist_plan(db: AsyncSession, clip_id: str, plan: SFXPlan) -> None:
        plan_json = plan.model_dump_json()
        plan_hash = hashlib.sha256(plan_json.encode()).hexdigest()
        
        existing_result = await db.execute(select(ClipSFXPlan).where(ClipSFXPlan.clip_id == clip_id))
        existing_plan = existing_result.scalar_one_or_none()
        
        if existing_plan:
            existing_plan.plan_json = plan_json
            existing_plan.plan_hash = plan_hash
        else:
            new_plan = ClipSFXPlan(
                clip_id=clip_id,
                plan_json=plan_json,
                plan_hash=plan_hash
            )
            db.add(new_plan)
        
        await db.commit()

    async def generate_plan(self, clip_id: str, db: AsyncSession, is_test: bool | None = None, explicit_request: bool = False) -> SFXPlan:
        # Verify trusted test context
        is_test_context = await self._is_trusted_test_clip(db, clip_id, explicit_is_test=is_test)

        # 1. Fetch Retention Data
        result = await db.execute(select(ClipRetention).where(ClipRetention.clip_id == clip_id))
        retention = result.scalar_one_or_none()
        if not retention:
            raise ValueError(f"Retention data not found for clip {clip_id}")

        risks = json.loads(retention.analysis_json)
        
        # 2. Fetch active SFX Assets
        assets_result = await db.execute(select(SFXAsset).where(SFXAsset.is_enabled == True))
        all_assets = list(assets_result.scalars().all())

        # In production context, filter out synthetic mock assets so test tones never enter real videos
        if not is_test_context:
            eligible_assets = [a for a in all_assets if not self._is_synthetic_mock_asset(a)]
        else:
            eligible_assets = all_assets

        if not eligible_assets:
            if is_test_context:
                logger.info(f"Test context: generating fallback synthetic SFX assets for clip {clip_id}")
                for cat in ["impact", "whoosh", "ambience"]:
                    sample_asset = await self._mock_generate_asset(db, cat, clip_id)
                    eligible_assets.append(sample_asset)
            else:
                logger.warning(
                    f"Production context: no active SFX assets found in sound library for clip {clip_id}. "
                    "Skipping synthetic audio generation."
                )
                empty_plan = SFXPlan(clip_id=clip_id, placements=[])
                await self._persist_plan(db, clip_id, empty_plan)
                return empty_plan

        placements = []
        # Sort risks chronologically
        risks = sorted(risks, key=lambda x: x.get("start_time", 0))

        for risk in risks:
            is_sfx_opp = ("sfx_opportunity" in risk.get("suggested_intervention_types", [])) or (risk.get("severity") in ["high", "critical"])
            # If explicit request, permit medium-severity zones only if the context has a defensible audio reason
            # (e.g. silence or low_audio). A zoom_push suggestion alone is NOT evidence that a sound effect should be inserted.
            if not is_sfx_opp and explicit_request and risk.get("severity") == "medium":
                reason_text = (risk.get("reason") or risk.get("primary_reason") or "").lower()
                interventions = risk.get("suggested_intervention_types", [])
                if ("silence" in reason_text or "low_audio" in reason_text) and "zoom_push" not in interventions:
                    is_sfx_opp = True

            if not is_sfx_opp:
                continue

            reason = (risk.get("reason") or risk.get("primary_reason") or "").lower()
            start = risk.get("start_time", 0)
            end = risk.get("end_time", 0)
            
            # Map risk reason to category
            category = "impact"
            ducking = False
            
            if "low_visual_motion" in reason or "static" in reason:
                category = "whoosh"
            elif "silence" in reason or "low_audio" in reason:
                category = "impact"
            elif "hook" in reason or "dropoff" in reason:
                category = "impact"
                ducking = True  # Ducking makes impact more pronounced

            # Find matching asset
            matching_assets = [a for a in eligible_assets if a.category == category]
            if not matching_assets:
                # fallback
                matching_assets = eligible_assets
                
            if matching_assets:
                # Deterministic selection based on timestamp
                asset_index = int(start * 100) % len(matching_assets)
                selected_asset = matching_assets[asset_index]
                
                # Check concurrency density limits
                concurrent_count = sum(1 for p in placements if max(0, min(end, p.end_time) - max(start, p.start_time)) > 0)
                if concurrent_count < self.max_concurrent_sfx:
                    # Determine duration (clamp to asset duration)
                    p_duration = min(end - start, selected_asset.duration)
                    if p_duration < 0.5:
                        p_duration = selected_asset.duration # minimum duration
                        
                    placement = SFXPlacement(
                        asset_id=selected_asset.artifact_id or selected_asset.id,
                        category=selected_asset.category,
                        start_time=start,
                        end_time=start + p_duration,
                        gain=self.default_gain,
                        ducking_enabled=ducking,
                        ducking_target_gain=self.ducking_target_gain if ducking else 0,
                        confidence=risk.get("risk_score", 1.0),
                        reason=category + " for " + reason
                    )
                    placements.append(placement)

        plan = SFXPlan(
            clip_id=clip_id,
            placements=placements
        )
        
        await self._persist_plan(db, clip_id, plan)
        return plan
