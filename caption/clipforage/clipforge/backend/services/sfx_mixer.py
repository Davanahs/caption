import math
import asyncio
from typing import Optional
from pathlib import Path
from backend.models.sfx import SFXPlan
from backend.models.hook import VoiceoverPlan
from backend.models.dubbing import DubbingResponse
from backend.services.artifact_manager import ArtifactManager

class SFXMixer:
    @staticmethod
    def db_to_linear(db: float) -> float:
        return 10 ** (db / 20)

    @staticmethod
    async def build_ffmpeg_command(
        video_input_path: str,
        sfx_plan: Optional[SFXPlan] = None,
        output_path: str = "output.mp4",
        artifact_manager: Optional[ArtifactManager] = None,
        voiceover_plan: Optional[VoiceoverPlan] = None,
        dubbing_response: Optional[DubbingResponse] = None
    ) -> list[str]:
        """
        Builds the FFmpeg command for mixing SFX and Voiceover into the video.
        Ensures ducking via timeline volume filters on the main audio track.
        """
        has_sfx = sfx_plan and sfx_plan.placements
        has_vo = voiceover_plan and voiceover_plan.segments
        has_dubbing = dubbing_response and dubbing_response.segments
        
        if not has_sfx and not has_vo and not has_dubbing:
            # Fallback if no SFX, VO, or Dubbing
            return [
                "ffmpeg", "-y", "-i", video_input_path, 
                "-c:v", "copy", "-c:a", "copy", "-movflags", "+faststart", "-f", "mp4", output_path
            ]
            
        cmd = ["ffmpeg", "-y", "-i", video_input_path]
        
        # Download assets to temp space
        audio_inputs = []
        
        # Combine SFX and VO placements into a generic list for mixing
        # (start_time, end_time, artifact_id, file_path, ducking_enabled, ducking_gain, gain)
        class AudioLayer:
            def __init__(self, start, end, aid, fpath, duck, d_gain, gain):
                self.start_time = start
                self.end_time = end
                self.artifact_id = aid
                self.file_path = fpath
                self.ducking_enabled = duck
                self.ducking_target_gain = d_gain
                self.gain = gain

        layers = []
        if has_sfx:
            for p in sfx_plan.placements:
                layers.append(AudioLayer(p.start_time, p.end_time, p.asset_id, None, p.ducking_enabled, p.ducking_target_gain, p.gain))
        if has_vo:
            for p in voiceover_plan.segments:
                # We need the artifact_id generated by voiceover engine.
                if p.artifact and p.artifact.artifact_id:
                    ducking_enabled = p.ducking_policy != "none"
                    layers.append(AudioLayer(p.start_time, p.end_time, p.artifact.artifact_id, None, ducking_enabled, -15.0, p.gain))
        if has_dubbing:
            for seg in dubbing_response.segments:
                if seg.generated_audio_reference:
                    # Dubbing always ducks original audio heavily
                    layers.append(AudioLayer(seg.start_time, seg.end_time, None, seg.generated_audio_reference, True, -20.0, 0.0))

        for layer in layers:
            if layer.file_path:
                asset_path = layer.file_path
            else:
                if not artifact_manager:
                    raise ValueError("artifact_manager required for layers without file_path")
                asset_path = await artifact_manager.resolve_artifact_path(layer.artifact_id)
            if not asset_path:
                raise ValueError(f"Could not resolve artifact path for layer")
            audio_inputs.append(asset_path)
            cmd.extend(["-i", asset_path])
            
        filter_complex = []
        
        # 1. Ducking on main audio [0:a]
        main_a = "0:a"
        ducking_count = 0
        for layer in layers:
            if layer.ducking_enabled:
                start = layer.start_time
                end = layer.end_time
                gain_db = layer.ducking_target_gain
                linear_gain = SFXMixer.db_to_linear(gain_db)
                out_label = f"duck{ducking_count}"
                filter_complex.append(
                    f"[{main_a}]volume=volume={linear_gain}:eval=frame:enable='between(t,{start},{end})'[{out_label}]"
                )
                main_a = out_label
                ducking_count += 1
                
        # 2. Additional audio processing
        mix_inputs = [f"[{main_a}]"]
        
        for i, layer in enumerate(layers):
            input_idx = i + 1
            delay_ms = int(layer.start_time * 1000)
            vol_db = layer.gain
            linear_vol = SFXMixer.db_to_linear(vol_db)
            
            audio_label = f"audio{i}"
            filter_complex.append(
                f"[{input_idx}:a]adelay={delay_ms}|{delay_ms},volume={linear_vol}[{audio_label}]"
            )
            mix_inputs.append(f"[{audio_label}]")
            
        # 3. Mix
        input_count = len(mix_inputs)
        mix_str = "".join(mix_inputs)
        filter_complex.append(f"{mix_str}amix=inputs={input_count}:duration=first:dropout_transition=0:normalize=0[outa]")
        
        # Assemble command
        cmd.extend([
            "-filter_complex", ";".join(filter_complex),
            "-map", "0:v",
            "-map", "[outa]",
            "-c:v", "copy",
            "-c:a", "aac",
            "-b:a", "192k",
            "-movflags", "+faststart",
            "-f", "mp4",
            output_path
        ])
        
        return cmd
